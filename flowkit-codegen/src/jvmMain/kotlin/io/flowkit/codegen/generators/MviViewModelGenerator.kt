                .addKdoc("State flow optimized for Swift interoperability.")
                .build(),

            // Side effects flow with iOS optimizations
            PropertySpec.builder(
                "sideEffects",
                ClassName("kotlinx.coroutines.flow", "Flow").parameterizedBy(sideEffectType)
            )
                .initializer("container.sideEffects")
                .addKdoc("Side effects flow with iOS-friendly emission patterns.")
                .build()
        )
    }

    /**
     * Builds the iOS container initializer.
     */
    private fun buildIosContainerInitializer(metadata: MviMetadata): String {
        return when (metadata.diConfig.framework) {
            DependencyInjection.KOIN -> {
                "${metadata.generationConfig.containerClassName}(scope, koin.get())"
            }

            else -> {
                "${metadata.generationConfig.containerClassName}(scope, repository)"
            }
        }
    }

    /**
     * Builds functions for the iOS ViewModel.
     */
    private fun buildIosViewModelFunctions(
        metadata: MviMetadata,
        intentType: TypeName,
        stateType: TypeName
    ): List<FunSpec> {
        return listOf(
            // Process intent function with iOS-friendly signature
            FunSpec.builder("processIntent")
                .addParameter("intent", intentType)
                .addKdoc(
                    """
                    Processes an intent asynchronously with iOS-optimized handling.
                    
                    This function is safe to call from Swift and properly handles
                    iOS memory management and threading concerns.
                    
                    @param intent The intent to process
                """.trimIndent()
                )
                .addCode(
                    CodeBlock.builder()
                        .addStatement("// Process intent with iOS-specific error handling")
                        .addStatement("kotlinx.coroutines.runBlocking {")
                        .indent()
                        .addStatement("container.processIntent(intent)")
                        .unindent()
                        .addStatement("}")
                        .build()
                )
                .build(),

            // Current state function
            FunSpec.builder("currentState")
                .returns(stateType)
                .addKdoc("Returns the current state value - Swift-friendly synchronous access.")
                .addStatement("return container.currentState()")
                .build(),

            // iOS-specific state observation helper
            FunSpec.builder("observeState")
                .addParameter(
                    "callback",
                    LambdaTypeName.get(parameters = arrayOf(stateType), returnType = UNIT)
                )
                .addKdoc(
                    """
                    Helper function for observing state changes from Swift.
                    
                    This provides a Swift-friendly way to observe state changes
                    without dealing with Kotlin Flow directly.
                    
                    @param callback Function called when state changes
                """.trimIndent()
                )
                .addCode(
                    CodeBlock.builder()
                        .addStatement("// Launch collection on appropriate scope for iOS")
                        .addStatement("kotlinx.coroutines.launch {")
                        .indent()
                        .addStatement("state.collect { newState ->")
                        .indent()
                        .addStatement("callback(newState)")
                        .unindent()
                        .addStatement("}")
                        .unindent()
                        .addStatement("}")
                        .build()
                )
                .build(),

            // iOS-specific side effects observation helper
            FunSpec.builder("observeSideEffects")
                .addParameter(
                    "callback", LambdaTypeName.get(
                        parameters = arrayOf(metadata.sideEffectInfo?.let {
                            ClassName(it.packageName, it.simpleName)
                        } ?: UNIT),
                        returnType = UNIT
                    ))
                .addKdoc(
                    """
                    Helper function for observing side effects from Swift.
                    
                    @param callback Function called when side effects are emitted
                """.trimIndent()
                )
                .addCode(
                    CodeBlock.builder()
                        .addStatement("kotlinx.coroutines.launch {")
                        .indent()
                        .addStatement("sideEffects.collect { sideEffect ->")
                        .indent()
                        .addStatement("callback(sideEffect)")
                        .unindent()
                        .addStatement("}")
                        .unindent()
                        .addStatement("}")
                        .build()
                )
                .build(),

            // iOS cleanup function
            FunSpec.builder("cleanup")
                .addKdoc("Performs iOS-specific cleanup. Call when the view is deallocated.")
                .addCode(
                    CodeBlock.builder()
                        .addStatement("container.close()")
                        .build()
                )
                .build()
        )
    }

    /**
     * Generates a common ViewModel for other platforms.
     */
    private fun generateCommonViewModel(metadata: MviMetadata) {
        val viewModelClass = buildCommonViewModelClass(metadata)

        val fileSpec = FileSpec.builder(
            packageName = metadata.generationConfig.outputPackage,
            fileName = "${metadata.generationConfig.viewModelClassName}Common"
        )
            .addFileComment("Generated by FlowKit CodeGen - Common ViewModel")
            .addFileComment("Platform-agnostic ViewModel for Desktop, Web, and other platforms")
            .addCommonImports()
            .addType(viewModelClass)
            .build()

        writeFile(fileSpec, metadata, "Common")
    }

