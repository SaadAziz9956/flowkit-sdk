    }

    /**
     * Guesses the repository type based on naming conventions.
     */
    private fun guessRepositoryType(metadata: MviMetadata): ClassName {
        val stateClassName = metadata.stateInfo.simpleName
        val repositoryName = stateClassName
            .replace("State", "Repository")
            .replace("Screen", "")

        return ClassName(metadata.stateInfo.packageName, repositoryName)
    }

    /**
     * Adds Android-specific imports to the file spec.
     */
    private fun FileSpec.Builder.addAndroidImports(metadata: MviMetadata): FileSpec.Builder {
        return apply {
            addImport("androidx.lifecycle", "ViewModel", "viewModelScope")
            addImport("kotlinx.coroutines", "launch")
            addImport("kotlinx.coroutines.flow", "StateFlow", "Flow")

            when (metadata.diConfig.framework) {
                DependencyInjection.HILT -> {
                    addImport("dagger.hilt.android.lifecycle", "HiltViewModel")
                    addImport("javax.inject", "Inject")
                }

                DependencyInjection.KOIN -> {
                    addImport("org.koin.android.ext.android", "get")
                }

                else -> { /* No additional imports */
                }
            }
        }
    }

    /**
     * Adds iOS-specific imports to the file spec.
     */
    private fun FileSpec.Builder.addIosImports(): FileSpec.Builder {
        return apply {
            addImport("kotlinx.coroutines", "CoroutineScope", "launch", "runBlocking")
            addImport("kotlinx.coroutines.flow", "StateFlow", "Flow", "collect")
        }
    }

    /**
     * Adds common imports to the file spec.
     */
    private fun FileSpec.Builder.addCommonImports(): FileSpec.Builder {
        return apply {
            addImport("kotlinx.coroutines", "CoroutineScope")
            addImport("kotlinx.coroutines.flow", "StateFlow", "Flow")
        }
    }

    /**
     * Writes the generated file to the appropriate output directory.
     */
    private fun writeFile(fileSpec: FileSpec, metadata: MviMetadata, suffix: String = "") {
        try {
            val fileName = if (suffix.isNotEmpty()) {
                "${metadata.generationConfig.viewModelClassName}$suffix"
            } else {
                metadata.generationConfig.viewModelClassName
            }

            // Create the file using KSP CodeGenerator
            val file = codeGenerator.createNewFile(
                dependencies = Dependencies(false), // No dependencies on source files
                packageName = metadata.generationConfig.outputPackage,
                fileName = fileName
            )

            // Write the content to the file
            file.bufferedWriter().use { writer ->
                fileSpec.writeTo(writer)
            }

            logger.info("📝 FlowKit: Generated ViewModel: $fileName.kt")

        } catch (exception: Exception) {
            logger.error("❌ FlowKit: Failed to write ViewModel: ${exception.message}")
            throw exception
        }
    }
}
