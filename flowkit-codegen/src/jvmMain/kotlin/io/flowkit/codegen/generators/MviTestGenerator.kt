    /**
     * Writes test files to the test source directory.
     */
    private fun writeTestFile(fileSpec: FileSpec, fileName: String) {
        try {
            // Create a new file using KSP CodeGenerator
            val file = codeGenerator.createNewFile(
                dependencies = Dependencies(false),
                packageName = fileSpec.packageName,
                fileName = fileName
            )

            // Write the FileSpec content to the file
            file.bufferedWriter().use { writer ->
                fileSpec.writeTo(writer)
            }

            logger.info("📝 FlowKit: Generated test file: $fileName.kt")

        } catch (exception: Exception) {
            logger.error("❌ FlowKit: Failed to write test file: ${exception.message}")
            throw exception
        }
    }
