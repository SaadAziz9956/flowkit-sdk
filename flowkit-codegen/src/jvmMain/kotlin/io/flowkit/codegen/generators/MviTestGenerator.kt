    /**
     * Builds parameters for the test state builder.
     */
    private fun buildTestStateParameters(metadata: MviMetadata): List<ParameterSpec> {
        return metadata.stateInfo.properties.map { property ->
            ParameterSpec.builder(property.name, property.type.asTypeName())
                .defaultValue(getDefaultValueForProperty(property))
                .build()
        }
    }

    /**
     * Gets appropriate default value for a property in tests.
     */
    private fun getDefaultValueForProperty(property: PropertyInfo): String {
        return when {
            property.defaultValue != null -> property.defaultValue
            property.type.contains("Boolean") -> "false"
            property.type.contains("String") -> "\"\""
            property.type.contains("Int") -> "0"
            property.type.contains("List") -> "emptyList()"
            property.isNullable -> "null"
            else -> "TODO(\"Provide default value for ${property.name}\")"
        }
    }

