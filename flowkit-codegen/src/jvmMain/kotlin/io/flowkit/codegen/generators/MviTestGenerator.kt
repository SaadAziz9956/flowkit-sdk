        return FunSpec.builder("createTestState")
            .addKdoc("Creates a test state with optional parameter overrides.")
            .returns(ClassName(metadata.stateInfo.packageName, metadata.stateInfo.simpleName))
            .addParameters(buildTestStateParameters(metadata))
            .addCode(
                CodeBlock.builder()
                    .addStatement("return ${metadata.stateInfo.simpleName}(")
                    .indent()
                    .apply {
                        metadata.stateInfo.properties.forEach { property ->
                            addStatement("${property.name} = ${property.name},")
