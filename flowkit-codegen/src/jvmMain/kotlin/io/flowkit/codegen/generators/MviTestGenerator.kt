/**
 * Generates comprehensive test suites for MVI components.
 *
 * This generator creates production-ready tests that cover:
 * - Unit tests for reducers (pure function testing)
 * - Integration tests for containers (state management testing)
 * - Property-based tests for state transitions
 * - Mock setups and test utilities
 * - Cross-platform test compatibility
 *
 * The generated tests follow testing best practices and provide excellent
 * coverage for MVI patterns while being easy to understand and maintain.
 */
class MviTestGenerator(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger
) {

    /**
     * Generates complete test suites for the MVI components.
     */
    fun generate(metadata: MviMetadata) {
        logger.info("🧪 FlowKit: Generating test suites for ${metadata.stateInfo.simpleName}")

        try {
            // Generate reducer tests (pure function tests)
            generateReducerTests(metadata)

            // Generate container tests (integration tests)
            generateContainerTests(metadata)

            // Generate test utilities and mocks
            generateTestUtilities(metadata)

            logger.info("✅ FlowKit: Successfully generated test suites")

        } catch (exception: Exception) {
            logger.error("❌ FlowKit: Failed to generate tests: ${exception.message}")
            throw exception
        }
    }

    /**
     * Generates unit tests for the reducer implementation.
     */
    private fun generateReducerTests(metadata: MviMetadata) {
        val testClass = buildReducerTestClass(metadata)

        val fileSpec = FileSpec.builder(
            packageName = metadata.generationConfig.outputPackage,
            fileName = "${metadata.generationConfig.reducerClassName}Test"
        )
            .addFileComment("Generated by FlowKit CodeGen - Reducer Unit Tests")
            .addFileComment("These tests verify the pure function behavior of the reducer")
            .addTestImports()
            .addType(testClass)
            .build()

        writeTestFile(fileSpec, "${metadata.generationConfig.reducerClassName}Test")
    }

    /**
     * Builds the reducer test class with comprehensive test coverage.
     */
    private fun buildReducerTestClass(metadata: MviMetadata): TypeSpec {
        val stateType = ClassName(metadata.stateInfo.packageName, metadata.stateInfo.simpleName)
        val intentType = metadata.intentInfo?.let {
            ClassName(it.packageName, it.simpleName)
        } ?: UNIT
        val sideEffectType = metadata.sideEffectInfo?.let {
            ClassName(it.packageName, it.simpleName)
        } ?: UNIT

        return TypeSpec.classBuilder("${metadata.generationConfig.reducerClassName}Test")
            .addKdoc(buildReducerTestKDoc(metadata))
            .addProperties(buildReducerTestProperties(metadata))
            .addFunctions(
                buildReducerTestFunctions(
                    metadata,
                    stateType,
                    intentType,
                    sideEffectType
                )
            )
            .build()
    }

    /**
     * Builds KDoc for the reducer test class.
     */
    private fun buildReducerTestKDoc(metadata: MviMetadata): CodeBlock {
        return CodeBlock.builder()
            .add("Unit tests for [${metadata.generationConfig.reducerClassName}].\n")
            .add("\n")
            .add("These tests verify that the reducer correctly implements MVI principles:\n")
            .add("- Pure function behavior (same input -> same output)\n")
            .add("- Immutable state handling\n")
            .add("- Correct side effect emission\n")
            .add("- Error handling and edge cases\n")
            .add("\n")
            .add("**Test Structure:**\n")
            .add("- Setup: Create initial state and dependencies\n")
            .add("- Action: Call reducer with intent\n")
            .add("- Verify: Assert new state and side effects\n")
            .build()
    }

    /**
     * Builds properties for the reducer test class.
     */
    private fun buildReducerTestProperties(metadata: MviMetadata): List<PropertySpec> {
        return listOf(
            // Mock repository
            PropertySpec.builder(
                "mockRepository",
                guessRepositoryType(metadata),
                KModifier.PRIVATE
            )
                .delegate("mockk<${guessRepositoryType(metadata).simpleName}>()")
                .addKdoc("Mock repository for testing reducer behavior")
                .build(),

            // Reducer under test
            PropertySpec.builder(
                "reducer",
                ClassName(
                    metadata.generationConfig.outputPackage,
                    metadata.generationConfig.reducerClassName
                ),
                KModifier.PRIVATE
            )
                .delegate("lazy { ${metadata.generationConfig.reducerClassName}(mockRepository) }")
                .addKdoc("Reducer instance under test")
                .build(),

            // Initial state
            PropertySpec.builder(
                "initialState",
                ClassName(metadata.stateInfo.packageName, metadata.stateInfo.simpleName),
                KModifier.PRIVATE
            )
                .initializer("${metadata.stateInfo.simpleName}()")
                .addKdoc("Initial state for testing")
                .build()
        )
    }

